/** Convert [path, value] entries into a nested override object (for merge()). */
export function entriesToOver(entries: [string, unknown][]): Record<string, unknown> {
  const root: Record<string, unknown> = {};
  for (const [path, value] of entries) {
    const keys = path.split('.');
    let cur = root;
    for (let i = 0; i < keys.length - 1; i++) {
      const k = keys[i];
      if (typeof cur[k] !== 'object' || cur[k] === null || Array.isArray(cur[k])) cur[k] = {};
      cur = cur[k] as Record<string, unknown>;
    }
    cur[keys[keys.length - 1]] = value;
  }
  return root;
}

/**
 * Recolor the current skin's theme from any base color (the "color sphere"
 * feature): derives all flat colors, recolors the cell tile on a canvas and
 * writes everything through setIn. Blocks are only touched when asked.
 */
export async function applyGlossyTheme(
  setIn: (path: string, value: unknown) => void,
  base: string,
  parts: { theme?: boolean; blocks?: boolean } = { theme: true, blocks: false },
): Promise<void> {
  const c = glossyThemeColors(base);
  if (parts.theme) {
    const tile = await recolorGlossyTile(c);
    for (const [p, v] of glossyEntries(c, tile)) setIn(p, v);
  }
  if (parts.blocks) {
    for (const [p, v] of glossyBlocksEntries()) setIn(p, v);
  }
}
