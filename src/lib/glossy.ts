// Glossy theme engine — derive a complete board/background/tray color scheme
// from ONE base color and recolor the extracted red-cell tile at runtime.
//
// The derivation mirrors scripts/make_glossy_tiles.py::glossy_theme_colors
// (offline tile generator) so bundled preset tiles == runtime color-sphere
// recolor for the same base hex. Keep the two in sync!

import { darken, hexToRgb, lighten, mix, rgbToHsl } from './color';

/** the tile extracted from the red mockup — hue 352, monochrome red family */
export const GLOSSY_SRC_TILE = '/textures/red-cell.png';
const SRC_HUE = 352;

export interface GlossyColors {
  base: string;
  bgTop: string;
  bgBottom: string;
  plate: string;
  cell: string;
  line: string;
  tray: string;
  iconBtn: string;
  iconIconColor: string;
  popupStyle: 'light' | 'dark';
  popupC1: string;
  scoreColor: string;
  scoreStroke: string;
  bestColor: string;
  flash: string;
  comboGlow: string;
  /** HSV remap params for the cell tile (see recolorGlossyTile) */
  tileDelta: number;
  tileSat: number;
  tileVLo: number;
  tileVHi: number;
}

/** Full color scheme from one base hex. Mirrors the Python generator. */
export function glossyThemeColors(base: string): GlossyColors {
  const { h, s, l } = rgbToHsl(base); // s, l in 0–100
  const light = l > 66;
  const dark = l < 22;

  let vLo = 0.22;
  let vHi = 0.95;
  if (light) [vLo, vHi] = [0.42, 0.99];
  else if (dark) [vLo, vHi] = [0.10, 0.62];
  else if (l < 45) [vLo, vHi] = [0.15, 0.92];

  // chromatic bases keep the source saturation; low-sat bases target
  // body S = base S (slate/pastel look), floor 0.06 for clean nero/bianco
  const tileSat = s >= 50 ? 1.0 : Math.min(1.0, Math.max(0.06, s / 100) / 0.96);

  return {
    base,
    bgTop: light ? lighten(base, 0.35) : darken(base, 0.07),
    bgBottom: darken(base, light ? 0.22 : 0.40),
    plate: darken(base, 0.64),
    cell: darken(base, 0.42),
    line: darken(base, 0.72),
    tray: darken(base, 0.70),
    iconBtn: darken(base, 0.22),
    iconIconColor: light ? '#3A3E48' : '#FFFFFF',
    popupStyle: light ? 'light' : 'dark',
    popupC1: light ? lighten(base, 0.55) : darken(base, 0.72),
    scoreColor: light ? '#2E3238' : '#FFFFFF',
    scoreStroke: light ? '#FFFFFF' : darken(base, 0.75),
    bestColor: light ? '#C08A00' : '#FFD75E',
    flash: mix(base, '#FFFFFF', 0.85),
    comboGlow: lighten(base, 0.18),
    tileDelta: ((h - SRC_HUE + 540) % 360) - 180,
    tileSat,
    tileVLo: vLo,
    tileVHi: vHi,
  };
}

