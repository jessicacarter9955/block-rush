// ------------------------------------------------------ runtime recolor ----

function rgbToHsvPx(r: number, g: number, b: number): [number, number, number] {
  const mx = Math.max(r, g, b);
  const mn = Math.min(r, g, b);
  const d = mx - mn;
  let h = 0;
  if (d !== 0) {
    if (mx === r) h = (((g - b) / d) % 6) * 60;
    else if (mx === g) h = ((b - r) / d + 2) * 60;
    else h = ((r - g) / d + 4) * 60;
    if (h < 0) h += 360;
  }
  return [h, mx === 0 ? 0 : d / mx, mx / 255];
}

function hsvToRgbPx(h: number, s: number, v: number): [number, number, number] {
  const hp = (((h % 360) + 360) % 360) / 60;
  const c = v * s;
  const x = c * (1 - Math.abs((hp % 2) - 1));
  let r = 0, g = 0, b = 0;
  if (hp < 1) [r, g, b] = [c, x, 0];
  else if (hp < 2) [r, g, b] = [x, c, 0];
  else if (hp < 3) [r, g, b] = [0, c, x];
  else if (hp < 4) [r, g, b] = [0, x, c];
  else if (hp < 5) [r, g, b] = [x, 0, c];
  else [r, g, b] = [c, 0, x];
  const m = v - c;
  return [r + m, g + m, b + m];
}

let cachedTile: { key: string; url: string } | null = null;

/**
 * Recolor the red source tile via HSV rotate + sat scale + value remap and
 * return a PNG data URL. Same math as scripts/make_glossy_tiles.py.
 */
export function recolorGlossyTile(c: GlossyColors): Promise<string> {
  const key = `${c.tileDelta}|${c.tileSat}|${c.tileVLo}|${c.tileVHi}`;
  if (cachedTile && cachedTile.key === key) return Promise.resolve(cachedTile.url);
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => {
      try {
        const cv = document.createElement('canvas');
        cv.width = img.naturalWidth || 256;
        cv.height = img.naturalHeight || 256;
        const ctx = cv.getContext('2d', { willReadFrequently: true });
        if (!ctx) throw new Error('no 2d context');
        ctx.drawImage(img, 0, 0, cv.width, cv.height);
        const data = ctx.getImageData(0, 0, cv.width, cv.height);
        const d = data.data;
        for (let i = 0; i < d.length; i += 4) {
          const [h, s, v] = rgbToHsvPx(d[i], d[i + 1], d[i + 2]);
          const [r, g, b] = hsvToRgbPx(
            h + c.tileDelta,
            Math.min(1, s * c.tileSat),
            c.tileVLo + (c.tileVHi - c.tileVLo) * v,
          );
          d[i] = Math.round(r * 255);
          d[i + 1] = Math.round(g * 255);
          d[i + 2] = Math.round(b * 255);
        }
        ctx.putImageData(data, 0, 0);
        const url = cv.toDataURL('image/png');
        cachedTile = { key, url };
        resolve(url);
      } catch (e) {
        reject(e);
      }
    };
    img.onerror = () => reject(new Error('tile load failed'));
    img.src = GLOSSY_SRC_TILE;
  });
}

